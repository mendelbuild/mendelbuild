// SaveConfig stores a generated config in the database.
func (g *Generator) SaveConfig(ctx context.Context, projectID uuid.UUID, configYAML string) (*domain.TrafficAllocationEnvoyConfig, error) {
	config := &domain.TrafficAllocationEnvoyConfig{
		ProjectID:  projectID,
		ConfigYAML: configYAML,
	}
	if err := g.db.CreateEnvoyConfig(ctx, config); err != nil {
		return nil, err
	}
	return config, nil
}

// GenerateAndSave generates and stores a config.
func (g *Generator) GenerateAndSave(ctx context.Context, projectID uuid.UUID, opts GenerateOptions) (*domain.TrafficAllocationEnvoyConfig, error) {
	yaml, err := g.Generate(ctx, projectID, opts)
	if err != nil {
		return nil, err
	}
	return g.SaveConfig(ctx, projectID, yaml)
}
